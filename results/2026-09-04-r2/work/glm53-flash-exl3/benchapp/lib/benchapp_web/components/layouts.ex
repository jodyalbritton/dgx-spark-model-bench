defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`, then
  restyled for Lumen — the nav bar (id `main-nav`) owns the current-page
  highlight (`aria-current="page"`), the phone-width menu toggle
  (id `nav-toggle`), and the theme control (id `theme-toggle`).
  """

  use BenchappWeb, :html

  embed_templates "layouts/*"

  @nav_links [
    %{key: "home", label: "Home", href: "/"},
    %{key: "about", label: "About", href: "/about"},
    %{key: "design", label: "Design", href: "/design"},
    %{key: "custom-designs", label: "Custom Designs", href: "/custom-designs"}
  ]

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  def app(assigns) do
    assigns = assign(assigns, :nav_links, @nav_links)

    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <div class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur">
        <div class="mx-auto w-full max-w-6xl px-4 sm:px-6">
          <nav id="main-nav" aria-label="Main" class="navbar min-h-14 gap-2 px-0">
            <div class="flex flex-1 items-center gap-2">
              <.link
                navigate={~p"/"}
                class="flex items-center gap-2 text-lg font-bold tracking-tight text-base-content"
                aria-label="Lumen home"
              >
                <span class="grid size-8 place-items-center rounded-xl bg-primary text-primary-content shadow-sm">
                  <JobyKit.CoreComponents.icon name="hero-beaker" class="size-5" />
                </span>
                <span>
                  Lumen<span class="text-primary">Lab</span>
                </span>
              </.link>
            </div>

            <%!-- Desktop links --%>
            <ul class="hidden gap-1 md:flex">
              <li :for={link <- @nav_links}>
                <.link
                  navigate={link.href}
                  aria-current={@active_nav == link.key && "page"}
                  class={[
                    "rounded-field px-3 py-2 text-sm font-medium text-base-content/70 transition-colors hover:bg-base-200 hover:text-base-content",
                    @active_nav == link.key && "bg-base-200 font-semibold text-base-content"
                  ]}
                >
                  {link.label}
                </.link>
              </li>
            </ul>

            <div class="flex items-center gap-1">
              <div id="theme-toggle" class="hidden sm:block">
                <JobyKit.CoreComponents.theme_toggle />
              </div>

              <button
                id="nav-toggle"
                type="button"
                class="btn btn-ghost btn-square btn-sm md:hidden"
                phx-click={
                  JS.toggle(
                    to: "#nav-menu",
                    in: "is-visible",
                    out: "is-hidden"
                  )
                }
                aria-expanded="false"
                aria-controls="nav-menu"
                aria-label="Toggle navigation menu"
              >
                <JobyKit.CoreComponents.icon name="hero-bars-3" class="size-5" />
              </button>
            </div>
          </nav>

          <%!-- Mobile menu --%>
          <ul id="nav-menu" class="is-hidden md:hidden">
            <li :for={link <- @nav_links}>
              <.link
                navigate={link.href}
                aria-current={@active_nav == link.key && "page"}
                class={[
                  "block rounded-field px-3 py-2 text-sm font-medium text-base-content/70 transition-colors hover:bg-base-200 hover:text-base-content",
                  @active_nav == link.key && "bg-base-200 font-semibold text-base-content"
                ]}
              >
                {link.label}
              </.link>
            </li>
          </ul>
        </div>
      </div>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex max-w-6xl flex-col gap-3 px-4 py-6 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p>© 2025 LumenLab · Instruments for curious teams</p>
          <p class="flex gap-2 font-mono">
            <.link navigate={~p"/design"} class="link link-hover">/design</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/custom-designs"} class="link link-hover">/custom-designs</.link>
          </p>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
