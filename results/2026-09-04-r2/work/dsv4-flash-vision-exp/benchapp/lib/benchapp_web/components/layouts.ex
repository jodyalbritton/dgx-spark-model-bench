defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content — the nav, the theme
  control, the footer, and the flash container are wired in here so
  every page gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge. The `app/1` nav is this app's own — it marks
  the current link with `aria-current="page"`, ships a mobile menu that
  collapses behind a toggle at phone widths, and hosts the theme toggle.
  """
  use BenchappWeb, :html

  embed_templates "layouts/*"

  @nav_links [
    %{key: "home", label: "Home", href: "/"},
    %{key: "about", label: "About", href: "/about"},
    %{key: "design", label: "Design", href: "/design"},
    %{key: "custom-designs", label: "Custom Designs", href: "/custom-designs"}
  ]

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  def app(assigns) do
    assigns = assign(assigns, nav_links: @nav_links)

    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <header class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur">
        <nav
          id="main-nav"
          class="navbar mx-auto w-full max-w-5xl gap-2 px-4 sm:px-6"
        >
          <div class="flex-1">
            <.link
              navigate={~p"/"}
              class="btn btn-ghost px-2 text-lg font-semibold normal-case tracking-tight"
            >
              <span class="flex items-center gap-2">
                <span class="badge badge-primary badge-sm p-1">
                  <span class="size-2 rounded-full bg-primary-content/20"></span>
                  <span class="size-2 rounded-full bg-primary-content/20"></span>
                </span>
                Lumen
              </span>
            </.link>
          </div>

          <ul class="menu menu-horizontal hidden items-center gap-1 px-1 md:flex">
            <li :for={item <- @nav_links}>
              <.link
                navigate={item.href}
                aria-current={@active_nav == item.key && "page"}
                class={["rounded-field", @active_nav == item.key && "menu-active"]}
              >
                {item.label}
              </.link>
            </li>
          </ul>

          <div class="flex items-center gap-1 pl-1">
            <JobyKit.CoreComponents.theme_toggle id="theme-toggle" />
            <JobyKit.CoreComponents.button
              id="nav-toggle"
              type="button"
              variant="ghost"
              size="sm"
              shape="square"
              class="md:hidden"
              aria-label="Toggle menu"
              phx-click={JS.toggle(to: "#mobile-menu")}
            >
              <.icon name="hero-bars-3" class="size-5" />
            </JobyKit.CoreComponents.button>
          </div>
        </nav>

        <div id="mobile-menu" class="hidden border-t border-base-300 md:hidden">
          <ul class="menu w-full gap-1 p-4">
            <li :for={item <- @nav_links}>
              <.link
                navigate={item.href}
                aria-current={@active_nav == item.key && "page"}
                class={["rounded-field", @active_nav == item.key && "menu-active"]}
              >
                {item.label}
              </.link>
            </li>
          </ul>
        </div>
      </header>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex max-w-5xl flex-col gap-3 px-4 py-6 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p>© Lumen · Crafted for calm, focused work.</p>
          <p class="flex gap-2 font-mono">
            <.link navigate={~p"/design"} class="link link-hover">/design</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/custom-designs"} class="link link-hover">/custom-designs</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link href={~p"/design.json"} class="link link-hover">/design.json</.link>
          </p>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
