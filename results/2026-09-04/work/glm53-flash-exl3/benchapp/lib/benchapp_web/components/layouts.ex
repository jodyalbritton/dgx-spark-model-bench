              <.icon name="hero-bolt" class="size-5" />
            </span>
            <span class="text-lg font-bold tracking-tight">Benchapp</span>
          </div>

          <nav aria-label="Main navigation" class="flex items-center gap-1">
            <ul class="flex items-center gap-1">
              <li>
                <.link
                  navigate={~p"/"}
                  aria-current={@active_nav == "home" && "page"}
                  class={[
