defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content — the nav, the theme
  control, the footer, and the flash container are wired in here so
  every page gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge, and `simple_nav/1` inside it draws neither.
  Splitting that between the two is what produces a seam where the
  centred nav's max-width ends.
  """
  use BenchappWeb, :html

  embed_templates "layouts/*"

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  attr :nav_links, :list, default: nil
  slot :inner_block, required: true

  @default_nav_links [
    %{key: "home", label: "Home", href: "/"},
    %{key: "design", label: "Design", href: "/design"},
    %{key: "custom-designs", label: "Custom Designs", href: "/custom-designs"}
  ]

  def app(assigns) do
    links = assigns[:nav_links] || @default_nav_links

    assigns =
      assign(assigns,
        nav_links: links,
        mobile_open: false
      )

    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <header
        id="top-nav"
        class="sticky top-0 z-40 border-b border-base-300/70 bg-base-100/85 backdrop-blur-xl"
      >
        <div class="mx-auto flex w-full max-w-6xl items-center justify-between gap-4 px-4 py-3 sm:px-6">
          <div class="flex items-center gap-2">
            <.link navigate={~p"/"} class="group flex items-center gap-2.5">
              <span class="flex size-9 items-center justify-center rounded-xl bg-gradient-to-br from-primary to-accent text-primary-content shadow-sm transition-transform group-hover:scale-105">
                <.icon name="hero-bolt" class="size-5" />
              </span>
              <span class="text-lg font-semibold tracking-tight">Benchapp</span>
            </.link>
          </div>

          <nav class="hidden items-center gap-1 md:flex" aria-label="Primary">
            <.link
              :for={link <- @nav_links}
              navigate={link.href}
              aria-current={@active_nav == link.key && "page"}
              class={[
                "rounded-lg px-3 py-1.5 text-sm font-medium transition-colors",
                if(@active_nav == link.key,
                  do: "bg-primary/10 text-primary",
                  else: "text-base-content/70 hover:bg-base-200 hover:text-base-content"
                )
              ]}
            >
              {link.label}
            </.link>
          </nav>

          <div class="flex items-center gap-2">
            <JobyKit.CoreComponents.theme_toggle />
            <JobyKit.CoreComponents.button
              variant="ghost"
              shape="circle"
              class="md:hidden"
              phx-click={JS.toggle(to: "#mobile-nav")}
              aria-label="Toggle navigation"
            >
              <.icon name="hero-bars-3" class="size-5" />
            </JobyKit.CoreComponents.button>
          </div>
        </div>

        <nav
          id="mobile-nav"
          class="hidden border-t border-base-300/70 px-4 pb-3 pt-2 md:hidden"
          aria-label="Mobile"
        >
          <div class="flex flex-col gap-1">
            <.link
              :for={link <- @nav_links}
              navigate={link.href}
              class={[
                "rounded-lg px-3 py-2 text-sm font-medium",
                if(@active_nav == link.key,
                  do: "bg-primary/10 text-primary",
                  else: "text-base-content/70 hover:bg-base-200"
                )
              ]}
            >
              {link.label}
            </.link>
          </div>
        </nav>
      </header>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
