defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content — the nav, the theme
  control, the footer, and the flash container are wired in here so
  every page gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge, and `simple_nav/1` inside it draws neither.
  Splitting that between the two is what produces a seam where the
  centred nav's max-width ends.
  """
  use BenchappWeb, :html

  alias BenchappWeb.CompositeComponents

  embed_templates "layouts/*"

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  def app(assigns) do
    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <div class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur">
        <CompositeComponents.main_nav active={@active_nav} brand="Lumen" />
      </div>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex w-full max-w-6xl flex-col gap-3 px-4 py-8 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p>Lumen — calm, realtime product surfaces.</p>
          <nav class="flex gap-4 font-mono">
            <.link navigate={~p"/about"} class="link link-hover">About</.link>
            <.link navigate={~p"/design"} class="link link-hover">/design</.link>
            <.link navigate={~p"/custom-designs"} class="link link-hover">/custom-designs</.link>
            <.link href={~p"/design.json"} class="link link-hover">/design.json</.link>
          </nav>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
