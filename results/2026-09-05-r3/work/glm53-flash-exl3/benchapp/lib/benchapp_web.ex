defmodule BenchappWeb do
  @moduledoc """
  The entrypoint for defining your web interface, such as controllers,
  components, channels, and so on. JobyKit-flavored: imports
  `JobyKit.CoreComponents` so `<.button>`, `<.input>`, `<.icon>`, etc.
  resolve to the kit-shipped wrappers.
  """

  def static_paths, do: ~w(assets fonts images favicon.ico robots.txt)

  def router do
    quote do
      use Phoenix.Router, helpers: false

      import Plug.Conn
      import Phoenix.Controller
      import Phoenix.LiveView.Router
    end
  end

  def channel do
    quote do
      use Phoenix.Channel
    end
  end

  def controller do
    quote do
      use Phoenix.Controller,
        formats: [:html, :json],
        layouts: [html: BenchappWeb.Layouts]

      import Plug.Conn

      unquote(verified_routes())
    end
  end

  def live_view do
    quote do
      use Phoenix.LiveView

      unquote(html_helpers())
    end
  end

  def live_component do
    quote do
      use Phoenix.LiveComponent

      unquote(html_helpers())
    end
  end

  def html do
    quote do
      use Phoenix.Component

      import Phoenix.Controller, only: [get_csrf_token: 0, view_module: 1, view_template: 1]

      unquote(html_helpers())
    end
  end

  defp html_helpers do
    quote do
      import Phoenix.HTML

      # Translation, as generated by phx.new. Dropping this while the app
      # still ships the Gettext backend leaves `gettext(...)` calls in
      # templates failing to compile.
      use Gettext, backend: BenchappWeb.Gettext

      # JobyKit-shipped wrappers: <.button>, <.card>, <.icon>, <.input>,
      # <.flash>, <.flash_group>, <.header>, <.list>, <.table>.
      import JobyKit.CoreComponents

      # This app's composites: <.empty_state>, <.feature_grid>.
      import BenchappWeb.CompositeComponents

      # Common modules used in templates
      alias Phoenix.LiveView.JS
      alias BenchappWeb.Layouts
      alias BenchappWeb.NavComponents

      unquote(verified_routes())
    end
  end

  def verified_routes do
    quote do
      use Phoenix.VerifiedRoutes,
        endpoint: BenchappWeb.Endpoint,
        router: BenchappWeb.Router,
        statics: BenchappWeb.static_paths()
    end
  end

  @doc """
  When used, dispatch to the appropriate controller/view/etc.
  """
  defmacro __using__(which) when is_atom(which) do
    apply(__MODULE__, which, [])
  end
end
