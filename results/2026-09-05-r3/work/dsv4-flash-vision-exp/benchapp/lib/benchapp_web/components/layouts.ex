defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content. The responsive nav, the
  theme control, and the flash container are wired in here so every page
  gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge, while the nav inside it draws neither.
  """

  use BenchappWeb, :html

  embed_templates "layouts/*"

  @nav_links [
    %{key: "home", label: "Home", href: "/"},
    %{key: "about", label: "About", href: "/about"},
    %{key: "design", label: "Design", href: "/design"},
    %{key: "custom", label: "Components", href: "/custom-designs"}
  ]

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  attr :mobile_open, :boolean, default: false
  attr :nav_links, :list, default: @nav_links
  slot :inner_block, required: true

  def app(assigns) do
    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <div
        id="main-nav"
        class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur"
      >
        <div class="mx-auto w-full max-w-5xl px-4 sm:px-6">
          <nav class="navbar min-h-16 gap-2 px-0" aria-label="Main navigation">
            <div class="flex flex-1 items-center gap-1">
              <.link
                navigate={~p"/"}
                class="flex items-center gap-2.5 px-1 text-base font-semibold tracking-tight normal-case"
              >
                <span class="flex size-8 items-center justify-center rounded-xl bg-primary/10 text-primary transition-transform group-hover:scale-105">
                  <.icon name="hero-fire" class="size-4" />
                </span>
                Hearth
              </.link>
            </div>

            <ul class="menu menu-horizontal hidden gap-1 px-1 md:flex">
              <li :for={link <- @nav_links}>
                <.link
                  navigate={link.href}
                  aria-current={@active_nav == link.key && "page"}
                  class={[
                    "rounded-field text-sm transition-colors",
                    @active_nav == link.key && "menu-active font-medium"
                  ]}
                >
                  {link.label}
                </.link>
              </li>
            </ul>

            <div class="flex items-center gap-1.5 pl-1">
              <.theme_toggle id="theme-toggle" />
              <.button
                id="nav-toggle"
                type="button"
                variant="ghost"
                shape="square"
                class="text-base-content/70 md:hidden"
                aria-label="Toggle navigation menu"
                aria-expanded={@mobile_open}
                phx-click="toggle-nav"
              >
                <.icon name="hero-bars-3" class="size-5" />
              </.button>
            </div>
          </nav>

          <div :if={@mobile_open} id="mobile-nav" class="pb-4 md:hidden">
            <ul class="menu w-full gap-1 p-0">
              <li :for={link <- @nav_links}>
                <.link
                  navigate={link.href}
                  aria-current={@active_nav == link.key && "page"}
                  class={[
                    "rounded-field text-base",
                    @active_nav == link.key && "menu-active font-medium"
                  ]}
                >
                  {link.label}
                </.link>
              </li>
            </ul>
          </div>
        </div>
      </div>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300 bg-base-100">
        <div class="mx-auto flex max-w-5xl flex-col gap-3 px-4 py-8 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p class="font-medium text-base-content/80">
            Hearth · A calmer home, one list at a time.
          </p>
          <nav aria-label="Footer" class="flex flex-wrap gap-4">
            <.link navigate={~p"/about"} class="link link-hover">About</.link>
            <.link navigate={~p"/design"} class="link link-hover">Design</.link>
            <.link navigate={~p"/custom-designs"} class="link link-hover">Components</.link>
            <.link navigate={~p"/"} class="link link-hover">Home</.link>
          </nav>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
