defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content — the nav, the theme
  control, the footer, and the flash container are wired in here so
  every page gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge.
  """
  use BenchappWeb, :html

  embed_templates "layouts/*"

  @nav_links [
    %{key: "home", label: "Home", href: "/"},
    %{key: "about", label: "About", href: "/about"},
    %{key: "design", label: "Design", href: "/design"},
    %{key: "components", label: "Components", href: "/custom-designs"}
  ]

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  def app(assigns) do
    assigns = assign(assigns, :nav_links, @nav_links)

    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <div class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur">
        <nav id="main-nav" class="mx-auto flex w-full max-w-6xl items-center gap-3 px-4 py-3 sm:px-6">
          <a href="/" class="flex items-center gap-2 font-semibold tracking-tight text-base-content">
            <span class="flex size-8 items-center justify-center rounded-lg bg-primary text-primary-content">
              <JobyKit.CoreComponents.icon name="hero-cloud" class="size-4" />
            </span>
            <span class="text-lg">Nimbus</span>
          </a>

          <ul class="menu menu-horizontal hidden items-center gap-1 px-1 md:flex">
            <li :for={link <- @nav_links}>
              <.link
                navigate={link.href}
                aria-current={@active_nav == link.key && "page"}
                class={["rounded-field", @active_nav == link.key && "menu-active"]}
              >
                {link.label}
              </.link>
            </li>
          </ul>

          <div class="ml-auto flex items-center gap-2">
            <JobyKit.CoreComponents.theme_toggle id="theme-toggle" />

            <.button
              id="nav-toggle"
              type="button"
              variant="ghost"
              size="sm"
              shape="square"
              class="md:hidden"
              aria-label="Toggle navigation"
              aria-expanded="false"
              aria-controls="mobile-menu"
              phx-click={
                JS.toggle(to: "#mobile-menu", display: "block")
                |> JS.toggle_attribute({"aria-expanded", "false", "true"}, to: "#nav-toggle")
              }
            >
              <JobyKit.CoreComponents.icon name="hero-bars-3" class="size-5" />
            </.button>
          </div>
        </nav>

        <div id="mobile-menu" class="hidden border-t border-base-300 bg-base-100/95 md:hidden">
          <ul class="menu w-full gap-1 p-3">
            <li :for={link <- @nav_links}>
              <.link
                navigate={link.href}
                aria-current={@active_nav == link.key && "page"}
                class={["rounded-field", @active_nav == link.key && "menu-active"]}
              >
                {link.label}
              </.link>
            </li>
          </ul>
        </div>
      </div>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex max-w-6xl flex-col gap-3 px-4 py-6 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p>Nimbus · weather intelligence for people who move.</p>
          <p class="flex gap-2">
            <.link navigate={~p"/about"} class="link link-hover">About</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/design"} class="link link-hover">Design</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/custom-designs"} class="link link-hover">Components</.link>
          </p>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
