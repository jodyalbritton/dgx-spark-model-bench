defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content — the nav, the theme
  control, the footer, and the flash container are wired in here so
  every page gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge, and `simple_nav/1` inside it draws neither.
  Splitting that between the two is what produces a seam where the
  centred nav's max-width ends.
  """
  use BenchappWeb, :html

  embed_templates "layouts/*"

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  def app(assigns) do
    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <div class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur">
        <div class="mx-auto w-full max-w-5xl px-4 sm:px-6">
          <BenchappWeb.Layouts.main_nav active={@active_nav} />
        </div>
      </div>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex max-w-5xl flex-col gap-3 px-4 py-6 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p>
            Benchapp · built with
            <.link
              href="https://github.com/jobycorp/joby_kit"
              class="link link-hover font-medium"
              target="_blank"
              rel="noopener"
            >
              JobyKit
            </.link>
          </p>
          <p class="flex gap-2 font-mono">
            <.link navigate={~p"/design"} class="link link-hover">/design</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/custom-designs"} class="link link-hover">/custom-designs</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link href={~p"/design.json"} class="link link-hover">/design.json</.link>
          </p>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end

  @links [
    %{key: "home", label: "Home", href: "/"},
    %{key: "about", label: "About", href: "/about"},
    %{key: "design", label: "Design", href: "/design"},
    %{key: "custom-designs", label: "Custom Designs", href: "/custom-designs"}
  ]

  @doc """
  Kit-style nav used inside `<Layouts.app>`: brand, links with
  `aria-current="page"`, a mobile menu behind `#nav-toggle`, and the
  theme toggle in both widths.
  """
  attr :active, :string, default: nil
  attr :rest, :global

  def main_nav(assigns) do
    assigns = assign(assigns, :links, @links)

    ~H"""
    <nav
      id="main-nav"
      data-component="BenchappWeb.Layouts.main_nav"
      class="navbar gap-2"
      aria-label="Main"
      {@rest}
    >
      <div class="flex flex-1 items-center gap-2">
        <.link navigate={~p"/"} class="btn btn-ghost px-2 text-lg font-semibold normal-case">
          Zephyr
        </.link>
      </div>

      <ul class="menu menu-horizontal hidden gap-1 px-1 md:flex">
        <li :for={link <- @links}>
          <.link
            navigate={link.href}
            aria-current={@active == link.key && "page"}
            class={["rounded-field", @active == link.key && "menu-active"]}
          >
            {link.label}
          </.link>
        </li>
      </ul>

      <div class="flex items-center gap-1">
        <JobyKit.CoreComponents.theme_toggle />
        <JobyKit.CoreComponents.button
          id="nav-toggle"
          type="button"
          variant="ghost"
          size="sm"
          shape="square"
          class="md:hidden"
          phx-click={JS.toggle(to: "#main-nav-menu", in: "opacity-0", time: 0)}
          aria-label="Toggle navigation menu"
          aria-expanded="false"
          aria-controls="main-nav-menu"
        >
          <JobyKit.CoreComponents.icon name="hero-bars-3" class="size-5" />
        </JobyKit.CoreComponents.button>
      </div>
    </nav>
    <ul id="main-nav-menu" class="menu hidden w-full rounded-box bg-base-200/50 md:hidden">
      <li :for={link <- @links}>
        <.link
          navigate={link.href}
          aria-current={@active == link.key && "page"}
          class={["rounded-field", @active == link.key && "menu-active"]}
        >
          {link.label}
        </.link>
      </li>
    </ul>
    """
  end
end
