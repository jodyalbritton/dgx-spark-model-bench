    },
    %{
      step: "5",
      rule: "None of the above?",
      detail: "Tailwind plus theme tokens — then expose the result as a wrapper and register it."
    }
  ]

  @lint_snippet """
  # See what's already registered before building anything
  curl http://localhost:4000/design.json | jq '.components[].data_component'

  # Then, after writing UI
  mix joby_kit.lint\
  """

  @impl true
  def mount(_params, _session, socket) do
    {:ok,
     assign(socket,
       page_title: "Home",
       build_order: @build_order,
       lint_snippet: @lint_snippet
     )}
  end

  @impl true
