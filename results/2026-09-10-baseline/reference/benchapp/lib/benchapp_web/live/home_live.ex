defmodule BenchappWeb.HomeLive do
  @moduledoc """
  Welcome page generated by `mix joby_kit.new`.

  It doubles as the worked example: every block on it is built from a
  registered kit wrapper, and each section's eyebrow names the component
  that renders it. If you're an agent picking up this app, this page is
  the shortest correct answer to "how do I build UI here".

  Edit freely — this file lives in your app, not in the kit. When you
  replace it, keep reaching for the wrappers it demonstrates.
  """

  use BenchappWeb, :live_view

  @build_order [
    %{step: "1", rule: "Domain composite exists?", detail: "Use it."},
    %{step: "2", rule: "Generic composite exists?", detail: "Use it — see /custom-designs."},
    %{step: "3", rule: "Core wrapper exists?", detail: "Use it — see /design."},
    %{
