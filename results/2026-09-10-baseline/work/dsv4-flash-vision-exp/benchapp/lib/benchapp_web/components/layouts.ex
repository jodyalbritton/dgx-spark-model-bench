defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content — the nav, the theme
  control, the footer, and the flash container are wired in here so
  every page gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge, and `main_nav/1` inside it draws neither.
  Splitting that between the two is what produces a seam where the
  centred nav's max-width ends.
  """
  use BenchappWeb, :html

  embed_templates "layouts/*"

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  @nav_links [
    %{key: "home", label: "Home", href: "/"},
    %{key: "research", label: "Research", href: "/research"},
    %{key: "about", label: "About", href: "/about"}
  ]

  def app(assigns) do
    assigns = assign(assigns, :nav_links, @nav_links)

    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <header class="sticky top-0 z-40 border-b border-base-300 bg-base-100">
        <div class="mx-auto max-w-6xl px-6 md:px-8">
          <nav id="main-nav" class="flex items-center justify-between gap-4 py-4">
            <.link navigate={~p"/"} class="flex items-center gap-2.5 font-semibold tracking-tight">
              <span aria-hidden="true" class="size-2.5 shrink-0 border border-secondary"></span>
              <span>JobyCorp</span>
            </.link>

            <ul class="hidden items-center gap-1 md:flex">
              <li :for={link <- @nav_links}>
                <.link
                  navigate={link.href}
                  aria-current={@active_nav == link.key && "page"}
                  class={[
                    "rounded-field px-3 py-2 text-sm font-medium text-base-content transition-colors duration-150",
                    @active_nav == link.key && "text-primary"
                  ]}
                >
                  {link.label}
                </.link>
              </li>
            </ul>

            <div class="flex items-center gap-1.5">
              <div id="theme-toggle">
                <JobyKit.CoreComponents.theme_toggle />
              </div>

              <.button
                id="nav-toggle"
                type="button"
                shape="circle"
                variant="ghost"
                size="sm"
                class="md:hidden"
                phx-click={JS.toggle(to: "#mobile-menu")}
                aria-label="Toggle navigation"
              >
                <.icon name="hero-bars-3" class="size-5" />
              </.button>
            </div>
          </nav>

          <div id="mobile-menu" class="hidden border-t border-base-300 pb-4 pt-2 md:hidden">
            <ul class="flex flex-col gap-1">
              <li :for={link <- @nav_links}>
                <.link
                  navigate={link.href}
                  aria-current={@active_nav == link.key && "page"}
                  phx-click={JS.toggle(to: "#mobile-menu")}
                  class={[
                    "rounded-field px-3 py-2 text-sm font-medium text-base-content transition-colors duration-150",
                    @active_nav == link.key && "text-primary"
                  ]}
                >
                  {link.label}
                </.link>
              </li>
            </ul>
          </div>
        </div>
      </header>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex max-w-6xl flex-col gap-3 px-6 py-8 text-sm md:flex-row md:items-center md:justify-between md:px-8">
          <div class="flex items-center gap-2.5">
            <span aria-hidden="true" class="size-2.5 shrink-0 border border-secondary"></span>
            <span class="font-semibold tracking-tight">JobyCorp</span>
          </div>

          <ul class="flex flex-wrap gap-5">
            <li :for={link <- @nav_links}>
              <.link
                navigate={link.href}
                class="text-base-content/70 transition-colors duration-150 hover:text-primary"
              >
                {link.label}
              </.link>
            </li>
          </ul>

          <p class="max-w-md text-base-content/70">
            Local models, measured on local hardware, results published in full.
          </p>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
