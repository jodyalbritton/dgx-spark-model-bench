defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render and supply only their content — the nav, the theme
  control, the footer, and the flash container are wired in here so
  every page gets them for free.

  The chrome owns its own surface: the sticky bar draws the background
  and border edge-to-edge, and `simple_nav/1` inside it draws neither.
  Splitting that between the two is what produces a seam where the
  centred nav's max-width ends.
  """
  use BenchappWeb, :html

  embed_templates "layouts/*"

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  @nav_items [
    %{key: "home", label: "Home", href: "/"},
    %{key: "about", label: "About", href: "/about"}
  ]

  def app(assigns) do
    assigns = assign(assigns, nav_items: @nav_items)

    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <div class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur">
        <nav id="main-nav" class="mx-auto w-full max-w-6xl px-4 sm:px-6">
          <div class="flex h-16 items-center justify-between gap-4">
            <.link
              navigate={~p"/"}
              class="flex items-center gap-2 text-lg font-semibold tracking-tight text-base-content"
            >
              <span class="flex size-8 items-center justify-center rounded-lg bg-primary text-primary-content">
                <.icon name="hero-sun" class="size-5" />
              </span>
              Fathom
            </.link>

            <div class="flex items-center gap-2">
              <JobyKit.CoreComponents.theme_toggle id="theme-toggle" />
              <JobyKit.CoreComponents.button
                type="button"
                shape="square"
                variant="ghost"
                id="nav-toggle"
                class="md:hidden"
                aria-label="Toggle menu"
                phx-click={JS.toggle_class("hidden", to: "#main-nav-links")}
              >
                <.icon name="hero-bars-3" class="size-5" />
              </JobyKit.CoreComponents.button>
            </div>
          </div>

          <div
            id="main-nav-links"
            class="hidden flex-col gap-1 border-t border-base-300 py-2 md:flex md:flex-row md:items-center md:gap-8 md:border-0 md:py-0"
          >
            <.link
              :for={item <- @nav_items}
              navigate={item.href}
              aria-current={@active_nav == item.key && "page"}
              class={[
                "rounded-lg px-3 py-2 text-sm font-medium transition-colors duration-150",
                @active_nav == item.key &&
                  "text-primary",
                @active_nav != item.key &&
                  "text-base-content/70 hover:bg-base-200/60 hover:text-base-content"
              ]}
            >
              {item.label}
            </.link>
          </div>
        </nav>
      </div>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex max-w-6xl flex-col gap-3 px-4 py-6 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p>Fathom · bright ideas, made simple</p>
          <p class="flex gap-2 font-mono">
            <.link navigate={~p"/design"} class="link link-hover">/design</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/custom-designs"} class="link link-hover">/custom-designs</.link>
          </p>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end
end
