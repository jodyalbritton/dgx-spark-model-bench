defmodule BenchappWeb.Layouts do
  @moduledoc """
  Layouts for BenchappWeb. Generated by `mix joby_kit.new`.

  Pages compose `<Layouts.app flash={@flash}>...` from inside their
  LiveView render. The chrome — sticky top navigation, theme control,
  footer, and flash container — is wired in here so every page gets it
  for free.
  """
  use BenchappWeb, :html

  embed_templates "layouts/*"

  attr :flash, :map, required: true
  attr :current_scope, :map, default: nil
  attr :active_nav, :string, default: nil
  slot :inner_block, required: true

  def app(assigns) do
    ~H"""
    <div class="flex min-h-dvh flex-col bg-base-100">
      <header class="sticky top-0 z-40 border-b border-base-300 bg-base-100/90 backdrop-blur">
        <nav
          id="main-nav"
          aria-label="Main"
          class="mx-auto flex w-full max-w-5xl items-center justify-between gap-3 px-4 py-3 sm:px-6"
        >
          <div class="flex items-center gap-2">
            <span class="flex size-8 items-center justify-center rounded-lg bg-primary/10 text-primary">
              <JobyKit.CoreComponents.icon name="hero-bolt" class="size-5" />
            </span>
            <.link navigate={~p"/"} class="text-lg font-bold tracking-tight">
              Lumen
            </.link>
          </div>

          <%!-- Desktop links --%>
          <ul class="hidden items-center gap-1 lg:flex">
            <li :for={link <- nav_links()}>
              <.nav_link href={link.href} label={link.label} active={@active_nav == link.id} />
            </li>
          </ul>

          <div class="flex items-center gap-2">
            <JobyKit.CoreComponents.theme_toggle id="theme-toggle" />
            <JobyKit.CoreComponents.button
              id="nav-toggle"
              variant="ghost"
              shape="square"
              size="sm"
              class="lg:hidden"
              aria-label="Toggle navigation menu"
              aria-controls="nav-menu"
              phx-click={JS.toggle(to: "#nav-menu")}
            >
              <JobyKit.CoreComponents.icon name="hero-bars-3" class="size-5" />
            </JobyKit.CoreComponents.button>
          </div>
        </nav>

        <%!-- Mobile menu --%>
        <ul id="nav-menu" class="hidden border-t border-base-200 bg-base-100 px-4 py-2 lg:hidden">
          <li :for={link <- nav_links()} class="py-1">
            <.nav_link
              href={link.href}
              label={link.label}
              active={@active_nav == link.id}
              class="block rounded-lg px-3 py-2"
            />
          </li>
        </ul>
      </header>

      <main class="flex-1">
        {render_slot(@inner_block)}
      </main>

      <footer class="border-t border-base-300">
        <div class="mx-auto flex max-w-5xl flex-col gap-3 px-4 py-6 text-xs text-base-content/60 sm:flex-row sm:items-center sm:justify-between sm:px-6">
          <p>© 2026 Lumen Labs · Light for deep work</p>
          <p class="flex gap-2 font-mono">
            <.link navigate={~p"/about"} class="link link-hover">About</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/design"} class="link link-hover">/design</.link>
            <span aria-hidden="true" class="opacity-40">·</span>
            <.link navigate={~p"/custom-designs"} class="link link-hover">/custom-designs</.link>
          </p>
        </div>
      </footer>

      <JobyKit.CoreComponents.flash_group flash={@flash} />
    </div>
    """
  end

  defp nav_links do
    [
      %{id: "home", label: "Home", href: ~p"/"},
      %{id: "about", label: "About", href: ~p"/about"},
      %{id: "design", label: "Design", href: ~p"/design"},
      %{id: "custom-designs", label: "Components", href: ~p"/custom-designs"}
    ]
  end

  attr :href, :string, required: true
  attr :label, :string, required: true
  attr :active, :boolean, default: false
  attr :class, :any, default: nil

  defp nav_link(assigns) do
    ~H"""
    <.link
      navigate={@href}
      aria-current={@active && "page"}
      class={[
        "text-sm font-medium transition-colors hover:text-primary",
        @active && "text-primary",
        !@active && "text-base-content/70",
        @class
      ]}
    >
      {@label}
    </.link>
    """
  end
end
